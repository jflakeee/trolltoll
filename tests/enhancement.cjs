'use strict';
const assert=require('node:assert/strict');
const rules=require('../data/enhancement.json');
const engine=require('../src/rules/enhancement.cjs');
const inventory=()=>({gold:100000,iron:10000,enhancementStone:1000,protectionStone:100});
const equipment=(level,failures=0)=>({enhancementLevel:level,highestEnhancementLevel:level,failuresByLevel:{[level]:failures}});
const attempt=(level,roll,protection=false,failures=0)=>engine.executeAttempt({rules,inventory:inventory(),equipment:equipment(level,failures),useProtection:protection,rng:()=>roll});
assert.equal(engine.validateRules(rules),true);
assert.equal(engine.attackBonus(0),0);
assert.equal(engine.attackBonus(8),59);
assert.equal(engine.attackBonus(15),136);
assert.equal(engine.getRule(rules,8).chance,.35);
assert.equal(attempt(0,.999).success,true);
assert.equal(attempt(8,.01).nextLevel,9);
assert.equal(attempt(8,.99).nextLevel,7);
assert.equal(attempt(8,.99,true).nextLevel,8);
assert.equal(attempt(4,.99).nextLevel,4);
assert.equal(attempt(8,.99,true).inventory.protectionStone,99);
assert.equal(attempt(8,.01,true).inventory.protectionStone,99);
assert.equal(attempt(8,.99).equipment.failuresByLevel[8],1);
assert.equal(attempt(8,.01,false,3).equipment.failuresByLevel[8],0);
let called=false;
const guaranteed=engine.executeAttempt({rules,inventory:inventory(),equipment:equipment(8,9),rng:()=>{called=true;return .999}});
assert.equal(guaranteed.success,true);
assert.equal(guaranteed.guaranteed,true);
assert.equal(called,false);
const insufficientInventory={...inventory(),iron:0}, initialEquipment=equipment(8);
const insufficient=engine.executeAttempt({rules,inventory:insufficientInventory,equipment:initialEquipment,rng:()=>{throw Error('Unexpected RNG')}});
assert.equal(insufficient.ok,false);
assert.deepEqual(insufficient.inventory,insufficientInventory);
assert.deepEqual(insufficient.equipment,initialEquipment);
assert.equal(attempt(8,.99).inventory.gold,98800);
assert.equal(attempt(8,.99).inventory.iron,9985);
assert.equal(attempt(8,.99).inventory.enhancementStone,994);
assert.equal(engine.executeAttempt({rules,inventory:inventory(),equipment:equipment(15)}).reason,'MAX_LEVEL');
assert.throws(()=>attempt(8,1),/RNG/);
assert.throws(()=>engine.validateRules({...rules,chance:[1]}),/chance/);
assert.equal(attempt(8,.99).equipment.highestEnhancementLevel,8);
console.log('enhancement tests passed');
