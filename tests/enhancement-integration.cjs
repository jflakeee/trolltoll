'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('game.js','utf8').replace(/\}\)\(\);\s*$/, 'globalThis.__test={p,progression,gain,grantGatherDrop,buttons,save};})();');
const storage=new Map();
const ctx2d=new Proxy({}, {get:(o,k)=>o[k]||(()=>{}),set:(o,k,v)=>(o[k]=v,true)});
const canvas={getContext:()=>ctx2d,addEventListener:()=>{},setPointerCapture:()=>{},dataset:{}};
const math=Object.create(Math);
math.random=()=>0;
const context={document:{hidden:false,getElementById:()=>canvas,addEventListener:()=>{}},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},innerWidth:390,innerHeight:740,devicePixelRatio:1,performance:{now:()=>0},requestAnimationFrame:()=>{},setInterval:()=>{},addEventListener:()=>{},console,Math:math};
vm.runInNewContext(source,context);
const {p,progression,gain,grantGatherDrop,buttons,save}=context.__test;
const e={id:'test-enemy',x:0,y:0,boss:false,xp:3,stat:'atk',dead:0};
gain(e);
assert.equal(progression.inventory.enhancementStone,1,'normal kill drops enhancement stone');
assert.equal(progression.rewardPity.normalKills,0);
grantGatherDrop({kind:'tree',x:0,y:0});
assert.equal(progression.inventory.ancientWood,1);
grantGatherDrop({kind:'stone',x:0,y:0});
assert.equal(progression.inventory.enhancementStone,2);
p.forge=true;p.stone=50;p.iron=50;p.gold=1000;
const craft=buttons.find(b=>b.id==='enhancementStone');
assert.equal(craft.enabled(),true);
craft.act();
assert.equal(progression.inventory.enhancementStone,3);
assert.equal(p.stone,38);
assert.equal(p.iron,46);
assert.equal(p.gold,900);
const protect=buttons.find(b=>b.id==='protectionStone');
assert.equal(protect.enabled(),false);
progression.inventory.enhancementStone=5;
assert.equal(protect.enabled(),true);
protect.act();
assert.equal(progression.inventory.enhancementStone,0);
assert.equal(progression.inventory.protectionStone,1);
assert.equal(p.iron,31);
assert.equal(p.gold,600);
save();
const persisted=JSON.parse(storage.get('trolltoll_web_v3'));
assert.equal(persisted.progression.inventory.protectionStone,1);
console.log('enhancement rewards and crafting tests passed');
