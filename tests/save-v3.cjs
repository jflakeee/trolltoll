'use strict';
const assert=require('node:assert/strict');
const {migrateSave,decodeSave,encodeSave,normalizeLegacy}=require('../src/rules/save-v3.cjs');
const v2={x:410,y:-25,level:18,xp:93,atk:74,def:21,hp:180,currentHp:130,kills:422,gold:1234,wood:30,stone:19,iron:8,workbench:true,forge:true,pick:true,axe:false,blade:true,club:true,armor:true,relics:2,relicBlade:false,bossKills:['boss0','boss1']};
const snapshot=JSON.stringify(v2);
const migrated=migrateSave(v2);
assert.equal(migrated.schemaVersion,3);
assert.equal(migrated.revision,0);
assert.deepEqual(migrated.legacy,v2);
assert.equal(JSON.stringify(v2),snapshot,'source save must remain unchanged');
assert.equal(migrated.progression.inventory.enhancementStone,0);
assert.equal(migrated.progression.equipment.mainWeapon.enhancementLevel,0);
assert.deepEqual(migrateSave(migrated),migrated,'v3 migration must be idempotent');
assert.deepEqual(decodeSave(encodeSave(migrated)),migrated,'save round trip');
const v3={...migrated,revision:7,progression:{...migrated.progression,inventory:{...migrated.progression.inventory,enhancementStone:23,protectionStone:4},equipment:{mainWeapon:{enhancementLevel:8,highestEnhancementLevel:10,failuresByLevel:{'8':4,'9':3}}}}};
assert.deepEqual(decodeSave(encodeSave(v3)),v3,'enhancement progress must persist');
const damaged=migrateSave({level:-2,atk:-4,hp:0,currentHp:999,wood:-30,bossKills:['boss0','boss0','bogus']});
assert.equal(damaged.legacy.level,1);
assert.equal(damaged.legacy.atk,10);
assert.equal(damaged.legacy.hp,1);
assert.equal(damaged.legacy.currentHp,1);
assert.equal(damaged.legacy.wood,0);
assert.deepEqual(damaged.legacy.bossKills,['boss0']);
assert.equal(normalizeLegacy({}).level,1);
assert.throws(()=>migrateSave(null),/INVALID_SAVE/);
assert.throws(()=>migrateSave({schemaVersion:4}),/UNSUPPORTED_SCHEMA/);
assert.throws(()=>migrateSave({schemaVersion:3}),/INVALID_V3_LEGACY/);
assert.throws(()=>decodeSave('{bad'),SyntaxError);
const normalized=migrateSave({...v3,progression:{...v3.progression,inventory:{enhancementStone:-5,protectionStone:Infinity},equipment:{mainWeapon:{enhancementLevel:99,highestEnhancementLevel:2,failuresByLevel:{'8':-1,'15':5,'2':3}}}}});
assert.equal(normalized.progression.inventory.enhancementStone,0);
assert.equal(normalized.progression.equipment.mainWeapon.enhancementLevel,15);
assert.deepEqual(normalized.progression.equipment.mainWeapon.failuresByLevel,{'2':3});
console.log('save v3 migration tests passed');
