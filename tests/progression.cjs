const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync('game.js','utf8').trimEnd();
assert.ok(source.endsWith('})();'));
const canvasContext=new Proxy({}, {get:(target,key)=>target[key]||(()=>{}),set:(target,key,value)=>(target[key]=value,true)});
const store=new Map();
const canvas={getContext:()=>canvasContext,addEventListener:()=>{},setPointerCapture:()=>{}};
const listeners={};
const context={document:{hidden:false,getElementById:()=>canvas,addEventListener:()=>{}},localStorage:{getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value)},performance:{now:()=>0},innerWidth:390,innerHeight:740,devicePixelRatio:1,addEventListener:(key,fn)=>listeners[key]=fn,setInterval:()=>{},requestAnimationFrame:()=>{},console};
const injection=' globalThis.__test={p,buttons,bosses,nodes,gain,zoneLimit,nextGoal,save};})();';
vm.runInNewContext(source.slice(0,-5)+injection,context,{filename:'game.js'});
const {p,buttons,bosses,nodes,gain,zoneLimit,nextGoal,save}=context.__test;
function craft(id){const b=buttons.find(item=>item.id===id);assert.ok(b,'missing '+id);assert.equal(b.show(),true,id+' visible');assert.equal(b.enabled(),true,id+' enabled');b.act();assert.equal(b.show(),false,id+' consumed');}
assert.equal(zoneLimit(),300);
assert.ok(nodes.some(n=>n.kind==='tree'&&Math.hypot(n.x,n.y)<300));
assert.ok(nodes.some(n=>n.kind==='stone'&&Math.hypot(n.x,n.y)<300));
assert.ok(nodes.some(n=>n.kind==='iron'&&Math.hypot(n.x,n.y)>540));
assert.equal(nodes.some(n=>n.kind==='iron'&&Math.hypot(n.x,n.y)<300),false);
p.wood=100;p.stone=100;
craft('bench');craft('club');craft('armor');
assert.equal(p.atk,16);assert.equal(p.def,9);
assert.match(nextGoal(),/수호자/);
const first=bosses[0];first.health=0;gain(first);
assert.equal(zoneLimit(),540);assert.equal(p.relics,1);assert.ok(p.bossKills.includes('boss0'));
// Existing players who already cleared the first boss must not be blocked by optional starter gear.
p.club=false;p.armor=false;
assert.match(nextGoal(),/제련소/);
p.club=true;p.armor=true;
craft('forge');
assert.match(nextGoal(),/채석 거인/);
const second=bosses[1];second.health=0;gain(second);
assert.equal(zoneLimit(),950);assert.equal(p.relics,2);
p.iron=100;
craft('pick');craft('axe');craft('blade');craft('relicBlade');
assert.equal(p.atk,54); // base 10 + club 6 + two boss rewards 10 + sword 8 + guardian sword 20
assert.equal(p.relics,0);
const third=bosses[2];third.health=0;gain(third);
assert.equal(p.bossKills.length,3);
assert.match(nextGoal(),/전 지역 해금 완료/);
// Repeat boss kills should grant ordinary combat rewards, not duplicate relics or unlocks.
const relicsBeforeRepeat=p.relics;
const maxBeforeRepeat=p.max;
const atkBeforeRepeat=p.atk;
const defBeforeRepeat=p.def;
third.health=0;gain(third);
assert.equal(p.bossKills.length,3,'repeat kills must not duplicate boss completion');
assert.equal(p.relics,relicsBeforeRepeat,'repeat kills must not grant extra relics');
assert.ok(p.max>=maxBeforeRepeat&&p.max<maxBeforeRepeat+20,'repeat kills may level up but must not grant first-clear HP bonus');
assert.equal(p.atk,atkBeforeRepeat+1,'repeat kills should retain ordinary enemy stat rewards');
assert.equal(p.def,defBeforeRepeat,'repeat kills must not grant first-clear defense bonus');
save();
const persisted=JSON.parse(store.get('trolltoll_web_v2'));
assert.equal(persisted.relicBlade,true);
assert.equal(persisted.bossKills.length,3);
assert.ok(persisted.wood>=0&&persisted.stone>=0&&persisted.iron>=0);
console.log('Progression test passed: resource zones, crafting, three boss unlocks, relic weapon and save');
